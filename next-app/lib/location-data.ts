export function getCitiesForState(stateName: string): string[] {
  if (!stateName) return [];
  const found = INDIAN_STATES_CITIES.find(
    (s) => s.state.toLowerCase() === stateName.trim().toLowerCase()
  );
  return found ? found.cities : [];
}
