"use client";

import React, { useState, useEffect, useCallback } from "react";

interface RedirectRule {
  id: string;
  source: string;
  destination: string;
  statusCode: number;
  contentType: "product" | "page" | "category" | "blog" | "custom";
  contentId?: string;
  active: boolean;
  autoGenerated: boolean;
  createdAt: string;
  updatedAt: string;
}

export default function RedirectManagementPanel() {
  const [redirects, setRedirects] = useState<RedirectRule[]>([]);
  const [loading, setLoading] = useState(true);
  const [search, setSearch] = useState("");
  const [typeFilter, setTypeFilter] = useState("all");
  const [statusFilter, setStatusFilter] = useState("all");
  const [msg, setMsg] = useState("");
  const [isError, setIsError] = useState(false);

  // New / Edit Redirect Modal State
  const [showModal, setShowModal] = useState(false);
  const [modalMode, setModalMode] = useState<"create" | "edit">("create");
  const [activeRuleId, setActiveRuleId] = useState<string | null>(null);
  const [modalForm, setModalForm] = useState({
    source: "",
    destination: "",
    contentType: "custom" as RedirectRule["contentType"],
    active: true,
  });
  const [savingModal, setSavingModal] = useState(false);
  const [modalError, setModalError] = useState("");

  const loadRedirects = useCallback(async () => {
    try {
      let url = "/api/admin/redirects?";
      const params = new URLSearchParams();
      if (search) params.set("search", search);
      if (typeFilter !== "all") params.set("contentType", typeFilter);
      if (statusFilter !== "all") params.set("active", statusFilter === "active" ? "true" : "false");
      url += params.toString();

      const res = await fetch(url);
      const data = await res.json();
      if (res.ok) {
        setRedirects(data.redirects || []);
      }
    } catch {
      // ignore
    }
    setLoading(false);
  }, [search, typeFilter, statusFilter]);

  useEffect(() => {
    loadRedirects();
  }, [loadRedirects]);

  const handleToggleActive = async (rule: RedirectRule) => {
    try {
      const res = await fetch("/api/admin/redirects", {
        method: "PATCH",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ id: rule.id, action: "toggle" }),
      });
      if (res.ok) {
        setMsg(`Redirect for "${rule.source}" ${rule.active ? "disabled" : "activated"}.`);
        setIsError(false);
        loadRedirects();
      } else {
        const d = await res.json();
        setMsg(d.error || "Failed to update redirect status.");
        setIsError(true);
      }
    } catch {
      setMsg("Network error.");
      setIsError(true);
    }
  };

  const handleDelete = async (rule: RedirectRule) => {
    if (!confirm(`Are you sure you want to delete the redirect from "${rule.source}" to "${rule.destination}"?`)) {
      return;
    }
    try {
      const res = await fetch(`/api/admin/redirects?id=${encodeURIComponent(rule.id)}`, {
        method: "DELETE",
      });
      if (res.ok) {
        setMsg(`Redirect "${rule.source}" removed successfully.`);
        setIsError(false);
        loadRedirects();
      } else {
        const d = await res.json();
        setMsg(d.error || "Failed to delete redirect.");
        setIsError(true);
      }
    } catch {
      setMsg("Network error.");
      setIsError(true);
    }
  };

  const openCreateModal = () => {
    setModalMode("create");
    setActiveRuleId(null);
    setModalForm({
      source: "",
      destination: "",
      contentType: "custom",
      active: true,
    });
    setModalError("");
    setShowModal(true);
  };

  const openEditModal = (rule: RedirectRule) => {
    setModalMode("edit");
    setActiveRuleId(rule.id);
    setModalForm({
      source: rule.source,
      destination: rule.destination,
      contentType: rule.contentType,
      active: rule.active,
    });
    setModalError("");
    setShowModal(true);
  };

  const handleSaveModal = async (e: React.FormEvent) => {
    e.preventDefault();
    setSavingModal(true);
    setModalError("");

    try {
      const endpoint = "/api/admin/redirects";
      const method = modalMode === "create" ? "POST" : "PATCH";
      const payload = modalMode === "create"
        ? modalForm
        : { id: activeRuleId, ...modalForm };

      const res = await fetch(endpoint, {
        method,
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(payload),
      });

      const data = await res.json();
      if (res.ok) {
        setShowModal(false);
        setMsg(modalMode === "create" ? "New redirect rule created successfully." : "Redirect rule updated successfully.");
        setIsError(false);
        loadRedirects();
      } else {
        setModalError(data.error || "Failed to save redirect rule.");
      }
    } catch {
      setModalError("Network error.");
    }
    setSavingModal(false);
  };

  const typeBadgeColors: Record<string, { bg: string; text: string }> = {
    product: { bg: "#e0e7ff", text: "#3730a3" },
    page: { bg: "#f3e8ff", text: "#6b21a8" },
    category: { bg: "#fef3c7", text: "#92400e" },
    blog: { bg: "#dcfce7", text: "#166534" },
    custom: { bg: "#f1f5f9", text: "#334155" },
  };

  return (
    <div style={{ maxWidth: 1100, margin: "0 auto", paddingBottom: 40 }}>
      {/* ── HEADER ── */}
      <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", marginBottom: 20, flexWrap: "wrap", gap: 12 }}>
        <div>
          <h3 style={{ font: "22px var(--font-display)", margin: 0, color: "var(--foreground)" }}>
            URL / 301 Redirect Management
          </h3>
          <p style={{ margin: "4px 0 0", fontSize: 13, color: "var(--muted)" }}>
            Manage permanent (301) redirects for Products, Pages, Categories, and Custom URLs with automatic loop prevention and chain flattening.
          </p>
        </div>
        <button
          onClick={openCreateModal}
          style={{
            padding: "9px 18px",
            background: "var(--purple)",
            color: "#fff",
            border: "none",
            borderRadius: 6,
            fontWeight: 600,
            fontSize: 13,
            cursor: "pointer",
            display: "inline-flex",
            alignItems: "center",
            gap: 6,
          }}
        >
          <span>+</span> Create 301 Redirect
        </button>
      </div>

      {/* ── NOTIFICATION ── */}
      {msg && (
        <div
          style={{
            padding: "10px 16px",
            marginBottom: 16,
            borderRadius: 6,
            fontSize: 13,
            fontWeight: 500,
            background: isError ? "#fef2f2" : "#f0fdf4",
            color: isError ? "#991b1b" : "#166534",
            border: `1px solid ${isError ? "#fecaca" : "#bbf7d0"}`,
          }}
        >
          {msg}
        </div>
      )}

      {/* ── FILTERS BAR ── */}
      <div
        style={{
          display: "flex",
          gap: 12,
          padding: 16,
          background: "#faf9f7",
          border: "1px solid var(--line)",
          borderRadius: 8,
          marginBottom: 20,
          flexWrap: "wrap",
        }}
      >
        <div style={{ flex: "1 1 240px" }}>
          <input
            type="text"
            placeholder="Search by source or target URL..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            style={{
              width: "100%",
              padding: "8px 12px",
              border: "1px solid var(--line)",
              borderRadius: 6,
              fontSize: 13,
              background: "#fff",
            }}
          />
        </div>

        <div style={{ display: "flex", gap: 8, alignItems: "center" }}>
          <label style={{ fontSize: 12, fontWeight: 600, color: "var(--muted)" }}>Type:</label>
          <select
            value={typeFilter}
            onChange={(e) => setTypeFilter(e.target.value)}
            style={{
              padding: "8px 12px",
              border: "1px solid var(--line)",
              borderRadius: 6,
              fontSize: 13,
              background: "#fff",
            }}
          >
            <option value="all">All Content Types</option>
            <option value="product">Products</option>
            <option value="page">CMS Pages</option>
            <option value="category">Categories</option>
            <option value="blog">Blog Articles</option>
            <option value="custom">Custom / Manual</option>
          </select>
        </div>

        <div style={{ display: "flex", gap: 8, alignItems: "center" }}>
          <label style={{ fontSize: 12, fontWeight: 600, color: "var(--muted)" }}>Status:</label>
          <select
            value={statusFilter}
            onChange={(e) => setStatusFilter(e.target.value)}
            style={{
              padding: "8px 12px",
              border: "1px solid var(--line)",
              borderRadius: 6,
              fontSize: 13,
              background: "#fff",
            }}
          >
            <option value="all">All Statuses</option>
            <option value="active">Active (301 Live)</option>
            <option value="inactive">Inactive (Disabled)</option>
          </select>
        </div>
      </div>

      {/* ── REDIRECTS TABLE ── */}
      <div
        style={{
          background: "#fff",
          border: "1px solid var(--line)",
          borderRadius: 8,
          overflow: "hidden",
        }}
      >
        <table style={{ width: "100%", borderCollapse: "collapse", fontSize: 13 }}>
          <thead>
            <tr style={{ background: "#f8fafc", borderBottom: "1px solid var(--line)", textAlign: "left" }}>
              <th style={{ padding: "12px 16px", fontWeight: 600, color: "#475569" }}>Source URL (Original)</th>
              <th style={{ padding: "12px 16px", fontWeight: 600, color: "#475569" }}>Destination URL (301 Target)</th>
              <th style={{ padding: "12px 16px", fontWeight: 600, color: "#475569" }}>Type</th>
              <th style={{ padding: "12px 16px", fontWeight: 600, color: "#475569" }}>Status</th>
              <th style={{ padding: "12px 16px", fontWeight: 600, color: "#475569" }}>Source / Trigger</th>
              <th style={{ padding: "12px 16px", fontWeight: 600, color: "#475569", textAlign: "right" }}>Actions</th>
            </tr>
          </thead>
          <tbody>
            {loading ? (
              <tr>
                <td colSpan={6} style={{ padding: 32, textAlign: "center", color: "var(--muted)" }}>
                  Loading redirects...
                </td>
              </tr>
            ) : redirects.length === 0 ? (
              <tr>
                <td colSpan={6} style={{ padding: 40, textAlign: "center", color: "var(--muted)" }}>
                  No URL redirects found matching current criteria.
                </td>
              </tr>
            ) : (
              redirects.map((r) => {
                const badge = typeBadgeColors[r.contentType] || typeBadgeColors.custom;
                return (
                  <tr key={r.id} style={{ borderBottom: "1px solid var(--line)", verticalAlign: "middle" }}>
                    <td style={{ padding: "12px 16px", fontFamily: "monospace", color: "#0f172a", wordBreak: "break-all" }}>
                      <span style={{ color: "#dc2626", fontWeight: 600 }}>{r.source}</span>
                    </td>
                    <td style={{ padding: "12px 16px", fontFamily: "monospace", color: "#0f172a", wordBreak: "break-all" }}>
                      <span style={{ color: "#16a34a", fontWeight: 600 }}>{r.destination}</span>
                    </td>
                    <td style={{ padding: "12px 16px" }}>
                      <span
                        style={{
                          padding: "3px 8px",
                          borderRadius: 4,
                          fontSize: 11,
                          fontWeight: 600,
                          textTransform: "uppercase",
                          background: badge.bg,
                          color: badge.text,
                        }}
                      >
                        {r.contentType}
                      </span>
                    </td>
                    <td style={{ padding: "12px 16px" }}>
                      <button
                        onClick={() => handleToggleActive(r)}
                        style={{
                          display: "inline-flex",
                          alignItems: "center",
                          gap: 6,
                          padding: "4px 10px",
                          borderRadius: 12,
                          border: "none",
                          fontSize: 11,
                          fontWeight: 600,
                          cursor: "pointer",
                          background: r.active ? "#dcfce7" : "#fee2e2",
                          color: r.active ? "#15803d" : "#b91c1c",
                        }}
                      >
                        <span
                          style={{
                            width: 6,
                            height: 6,
                            borderRadius: "50%",
                            background: r.active ? "#16a34a" : "#dc2626",
                          }}
                        />
                        {r.active ? "301 Active" : "Disabled"}
                      </button>
                    </td>
                    <td style={{ padding: "12px 16px", fontSize: 12, color: "var(--muted)" }}>
                      {r.autoGenerated ? "🤖 Auto (Slug Change)" : "✍️ Manual"}
                    </td>
                    <td style={{ padding: "12px 16px", textAlign: "right" }}>
                      <div style={{ display: "inline-flex", gap: 8 }}>
                        <button
                          onClick={() => openEditModal(r)}
                          style={{
                            padding: "4px 8px",
                            border: "1px solid var(--line)",
                            background: "#fff",
                            borderRadius: 4,
                            cursor: "pointer",
                            fontSize: 12,
                          }}
                        >
                          ✏️ Edit
                        </button>
                        <button
                          onClick={() => handleDelete(r)}
                          style={{
                            padding: "4px 8px",
                            border: "1px solid #fecaca",
                            background: "#fff5f5",
                            color: "#dc2626",
                            borderRadius: 4,
                            cursor: "pointer",
                            fontSize: 12,
                          }}
                        >
                          🗑️
                        </button>
                      </div>
                    </td>
                  </tr>
                );
              })
            )}
          </tbody>
        </table>
      </div>

      {/* ── CREATE / EDIT MODAL ── */}
      {showModal && (
        <div
          style={{
            position: "fixed",
            inset: 0,
            background: "rgba(0,0,0,0.45)",
            display: "flex",
            alignItems: "center",
            justifyContent: "center",
            zIndex: 9999,
            padding: 16,
          }}
        >
          <div
            style={{
              background: "#fff",
              borderRadius: 8,
              padding: 24,
              maxWidth: 500,
              width: "100%",
              boxShadow: "0 20px 25px -5px rgba(0,0,0,0.1), 0 8px 10px -6px rgba(0,0,0,0.1)",
            }}
          >
            <h4 style={{ margin: "0 0 16px", font: "18px var(--font-display)", color: "var(--foreground)" }}>
              {modalMode === "create" ? "Add New 301 Redirect" : "Edit 301 Redirect"}
            </h4>

            {modalError && (
              <div
                style={{
                  padding: "8px 12px",
                  borderRadius: 6,
                  background: "#fef2f2",
                  color: "#991b1b",
                  border: "1px solid #fecaca",
                  fontSize: 12,
                  marginBottom: 14,
                }}
              >
                {modalError}
              </div>
            )}

            <form onSubmit={handleSaveModal} style={{ display: "grid", gap: 14 }}>
              <div>
                <label style={{ display: "block", fontSize: 12, fontWeight: 600, marginBottom: 4 }}>
                  Source URL Path *
                </label>
                <input
                  type="text"
                  placeholder="/old-page or /products/old-slug"
                  value={modalForm.source}
                  onChange={(e) => setModalForm({ ...modalForm, source: e.target.value })}
                  required
                  style={{
                    width: "100%",
                    padding: "9px 12px",
                    border: "1px solid var(--line)",
                    borderRadius: 6,
                    fontSize: 13,
                    fontFamily: "monospace",
                  }}
                />
                <span style={{ fontSize: 11, color: "var(--muted)", display: "block", marginTop: 3 }}>
                  Must start with '/' (e.g. /products/lumine-c-v1)
                </span>
              </div>

              <div>
                <label style={{ display: "block", fontSize: 12, fontWeight: 600, marginBottom: 4 }}>
                  Target Destination URL Path *
                </label>
                <input
                  type="text"
                  placeholder="/new-page or /products/new-slug"
                  value={modalForm.destination}
                  onChange={(e) => setModalForm({ ...modalForm, destination: e.target.value })}
                  required
                  style={{
                    width: "100%",
                    padding: "9px 12px",
                    border: "1px solid var(--line)",
                    borderRadius: 6,
                    fontSize: 13,
                    fontFamily: "monospace",
                  }}
                />
                <span style={{ fontSize: 11, color: "var(--muted)", display: "block", marginTop: 3 }}>
                  Internal relative path only (e.g. /products/lumine-c-daily-serum)
                </span>
              </div>

              <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: 12 }}>
                <div>
                  <label style={{ display: "block", fontSize: 12, fontWeight: 600, marginBottom: 4 }}>
                    Content Type
                  </label>
                  <select
                    value={modalForm.contentType}
                    onChange={(e) => setModalForm({ ...modalForm, contentType: e.target.value as RedirectRule["contentType"] })}
                    style={{
                      width: "100%",
                      padding: "9px 12px",
                      border: "1px solid var(--line)",
                      borderRadius: 6,
                      fontSize: 13,
                    }}
                  >
                    <option value="custom">Custom</option>
                    <option value="product">Product</option>
                    <option value="page">CMS Page</option>
                    <option value="category">Category</option>
                    <option value="blog">Blog</option>
                  </select>
                </div>

                <div>
                  <label style={{ display: "block", fontSize: 12, fontWeight: 600, marginBottom: 4 }}>
                    HTTP Status
                  </label>
                  <input
                    type="text"
                    disabled
                    value="301 (Permanent Redirect)"
                    style={{
                      width: "100%",
                      padding: "9px 12px",
                      border: "1px solid var(--line)",
                      borderRadius: 6,
                      fontSize: 13,
                      background: "#f1f5f9",
                      color: "#64748B",
                    }}
                  />
                </div>
              </div>

              <div style={{ marginTop: 8 }}>
                <label style={{ display: "flex", alignItems: "center", gap: 8, fontSize: 13, cursor: "pointer" }}>
                  <input
                    type="checkbox"
                    checked={modalForm.active}
                    onChange={(e) => setModalForm({ ...modalForm, active: e.target.checked })}
                  />
                  <span>Active immediately upon saving</span>
                </label>
              </div>

              <div style={{ display: "flex", justifyContent: "flex-end", gap: 10, marginTop: 12 }}>
                <button
                  type="button"
                  onClick={() => setShowModal(false)}
                  style={{
                    padding: "9px 16px",
                    border: "1px solid var(--line)",
                    background: "#fff",
                    borderRadius: 6,
                    fontSize: 13,
                    cursor: "pointer",
                  }}
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  disabled={savingModal}
                  style={{
                    padding: "9px 20px",
                    background: "var(--purple)",
                    color: "#fff",
                    border: "none",
                    borderRadius: 6,
                    fontWeight: 600,
                    fontSize: 13,
                    cursor: "pointer",
                  }}
                >
                  {savingModal ? "Saving…" : modalMode === "create" ? "Save Redirect" : "Update Redirect"}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
}
